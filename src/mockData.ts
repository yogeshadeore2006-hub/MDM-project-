export const generateChartHistoryData = (baseTemp = 28.6, baseHum = 64, baseAqi = 72, baseCo2 = 421) => {
  const data = [];
  const now = new Date();
  for (let i = 30; i >= 0; i--) {
    const d = new Date(now.getTime() - i * 4000);
    const timeStr = d.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit', second: '2-digit' });
    data.push({
      time: timeStr,
      temperature: +(baseTemp + Math.sin(i * 0.3) * 0.8 + (Math.random() - 0.5) * 0.4).toFixed(1),
      humidity: Math.round(baseHum + Math.cos(i * 0.2) * 2 + (Math.random() - 0.5) * 2),
      air_quality: Math.round(baseAqi + Math.sin(i * 0.4) * 3 + (Math.random() - 0.5) * 3),
      co2: Math.round(baseCo2 + Math.cos(i * 0.3) * 8 + (Math.random() - 0.5) * 5),
    });
  }
  return data;
};
